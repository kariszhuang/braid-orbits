//! Geometric versus combinatorial all-smoothness for four-point covers.
//!
//! Conventions follow ../common/braid.py: composition is
//! rightmost-first, (x*y)[i] = x[y[i]], g1 g2 g3 g4 = 1, and the six moves are
//! sigma_j: (a,b) -> (a b a^-1, a) and its inverse (a,b) -> (b, b^-1 a b).
//!
//! At the cusp {12|34} of a state the admissible cover has one source
//! component for each orbit of <g1,g2> (over the bubble) and of <g3,g4>
//! (over the main target component), and one node for each cycle of g1 g2.
//! The stable limit of the source is smooth iff this bipartite dual graph is a
//! tree with at most one vertex of positive genus ("geometric smoothness").
//! The project's combinatorial notion asks more: one of the two pair sides is
//! index-additive, i.e. every vertex on that side is a genus-0 leaf.
//! Every cusp of every state is the {12|34} cusp of some state in the full
//! orbit, so checking {12|34} on all states checks the whole family.
use std::collections::HashMap;

const MAXD: usize = 8;
type P = [u8; MAXD];

#[derive(Clone, Copy)]
struct Cx { n: usize }
impl Cx {
    fn id(&self) -> P { let mut p = [0u8; MAXD]; for i in 0..MAXD { p[i] = i as u8; } p }
    fn mul(&self, a: &P, b: &P) -> P { let mut c = self.id(); for i in 0..self.n { c[i] = a[b[i] as usize]; } c }
    fn inv(&self, a: &P) -> P { let mut c = self.id(); for i in 0..self.n { c[a[i] as usize] = i as u8; } c }
    fn is_id(&self, a: &P) -> bool { (0..self.n).all(|i| a[i] as usize == i) }
    fn cyc_lens(&self, a: &P) -> Vec<usize> {
        let mut seen = [false; MAXD]; let mut out = vec![];
        for s in 0..self.n { if seen[s] { continue; } let mut l = 0; let mut x = s;
            while !seen[x] { seen[x] = true; x = a[x] as usize; l += 1; } out.push(l); }
        out
    }
    fn ind(&self, a: &P) -> usize {
        let mut seen = 0u16; let mut c = 0;
        for s in 0..self.n { if seen >> s & 1 == 1 { continue; } c += 1; let mut x = s;
            while seen >> x & 1 == 0 { seen |= 1 << x; x = a[x] as usize; } }
        self.n - c
    }
    fn ncyc(&self, a: &P) -> usize { self.n - self.ind(a) }
    /// 840 * sum over cycles of 1/length (840 = lcm(1..8)).
    fn h840(&self, a: &P) -> i64 { self.cyc_lens(a).iter().map(|&l| 840 / l as i64).sum() }
    /// orbit labels of the group generated by gens
    fn orbits(&self, gens: &[&P]) -> ([u8; MAXD], usize) {
        let mut lab = [u8::MAX; MAXD]; let mut k = 0u8;
        for s in 0..self.n {
            if lab[s] != u8::MAX { continue; }
            let mut stack = vec![s]; lab[s] = k;
            while let Some(x) = stack.pop() {
                for g in gens { let y = g[x] as usize; if lab[y] == u8::MAX { lab[y] = k; stack.push(y); } }
            }
            k += 1;
        }
        (lab, k as usize)
    }
    /// number of cycles of a lying in each orbit (orbit labels lab, count no)
    fn cyc_per_orbit(&self, a: &P, lab: &[u8; MAXD], no: usize) -> Vec<i64> {
        let mut out = vec![0i64; no]; let mut seen = [false; MAXD];
        for s in 0..self.n { if seen[s] { continue; } out[lab[s] as usize] += 1; let mut x = s;
            while !seen[x] { seen[x] = true; x = a[x] as usize; } }
        out
    }
}

/// (geometrically smooth, combinatorially smooth) at the {12|34} cusp.
fn cusp(cx: &Cx, t: &[P; 4]) -> (bool, bool) {
    let n = cx.n;
    let p = cx.mul(&t[0], &t[1]);
    let ip = cx.ind(&p);
    let comb = ip == cx.ind(&t[0]) + cx.ind(&t[1]) || ip == cx.ind(&t[2]) + cx.ind(&t[3]);
    let (la, na) = cx.orbits(&[&t[0], &t[1]]);
    let (lb, nb) = cx.orbits(&[&t[2], &t[3]]);
    let ncyc = cx.ncyc(&p);
    if ncyc + 1 != na + nb { return (false, comb); } // connected by transitivity; tree iff E = V - 1
    let mut size_a = vec![0i64; na]; let mut size_b = vec![0i64; nb];
    for x in 0..n { size_a[la[x] as usize] += 1; size_b[lb[x] as usize] += 1; }
    let ca = [cx.cyc_per_orbit(&t[0], &la, na), cx.cyc_per_orbit(&t[1], &la, na), cx.cyc_per_orbit(&p, &la, na)];
    let cb = [cx.cyc_per_orbit(&t[2], &lb, nb), cx.cyc_per_orbit(&t[3], &lb, nb), cx.cyc_per_orbit(&p, &lb, nb)];
    let mut positive = 0;
    for i in 0..na { let twog = size_a[i] + 2 - ca[0][i] - ca[1][i] - ca[2][i]; assert!(twog >= 0 && twog % 2 == 0); if twog > 0 { positive += 1; } }
    for i in 0..nb { let twog = size_b[i] + 2 - cb[0][i] - cb[1][i] - cb[2][i]; assert!(twog >= 0 && twog % 2 == 0); if twog > 0 { positive += 1; } }
    (positive <= 1, comb)
}

fn mv(cx: &Cx, t: &[P; 4], m: usize) -> [P; 4] {
    let j = m % 3; let a = t[j]; let b = t[j + 1]; let mut u = *t;
    if m < 3 { u[j] = cx.mul(&a, &cx.mul(&b, &cx.inv(&a))); u[j + 1] = a; }
    else { u[j] = b; u[j + 1] = cx.mul(&cx.inv(&b), &cx.mul(&a, &b)); }
    u
}

type Key = [u8; 3 * MAXD];
fn canonical(cx: &Cx, t: &[P; 4]) -> Key {
    let n = cx.n; let gi: Vec<P> = t.iter().map(|p| cx.inv(p)).collect();
    let mut best = [u8::MAX; 3 * MAXD];
    for r in 0..n {
        let mut lab = [u8::MAX; MAXD]; let mut order = [0u8; MAXD]; let mut len = 1; lab[r] = 0; order[0] = r as u8;
        let mut i = 0;
        while i < len { let x = order[i] as usize; i += 1;
            for g in t.iter().chain(gi.iter()) { let y = g[x] as usize; if lab[y] == u8::MAX { lab[y] = len as u8; order[len] = y as u8; len += 1; } } }
        let mut key = [u8::MAX; 3 * MAXD];
        for j in 0..3 { for k in 0..n { key[j * MAXD + k] = lab[t[j][order[k] as usize] as usize]; } }
        if key < best { best = key; }
    }
    best
}
fn unpack(cx: &Cx, k: &Key) -> [P; 4] {
    let mut t = [cx.id(); 4];
    for j in 0..3 { for i in 0..cx.n { t[j][i] = k[j * MAXD + i]; } }
    t[3] = cx.inv(&cx.mul(&t[0], &cx.mul(&t[1], &t[2])));
    t
}

struct OrbitResult { states: Vec<Key>, geo: bool, comb: bool, lam12_840: i64, bad_word: Option<usize> }

/// BFS of the full six-move orbit; stops early (geo=false) at the first
/// geometrically non-smooth state unless `full` is set.
fn orbit(cx: &Cx, t0: &[P; 4], cap: usize, full: bool) -> Option<OrbitResult> {
    let root = canonical(cx, t0);
    let mut idx: HashMap<Key, usize> = HashMap::new(); idx.insert(root, 0);
    let mut st = vec![root]; let mut i = 0; let mut geo = true; let mut comb = true; let mut bad = None;
    while i < st.len() {
        let u = unpack(cx, &st[i]);
        let (g, c) = cusp(cx, &u);
        if !g { geo = false; if bad.is_none() { bad = Some(i); } if !full { break; } }
        if !c { comb = false; }
        for m in 0..6 {
            let k = canonical(cx, &mv(cx, &u, m));
            if !idx.contains_key(&k) { idx.insert(k, st.len()); st.push(k); if st.len() > cap { return None; } }
        }
        i += 1;
    }
    let mut lam = 0i64;
    if geo || full {
        let base: i64 = 840 * cx.n as i64 - t0.iter().map(|p| cx.h840(p)).sum::<i64>();
        let mut s = 0i64;
        for k in &st {
            let u = unpack(cx, k);
            let ab = cx.mul(&u[0], &u[1]); let bc = cx.mul(&u[1], &u[2]);
            let third = cx.mul(&u[0], &cx.mul(&u[1], &cx.mul(&u[2], &cx.inv(&u[1]))));
            s += cx.h840(&ab) + cx.h840(&bc) + cx.h840(&third);
        }
        lam = base * st.len() as i64 + s; // = 840 * 12 * deg(lambda) on the N-state curve
    }
    Some(OrbitResult { states: st, geo, comb, lam12_840: lam, bad_word: bad })
}

fn all_perms(n: usize) -> Vec<P> {
    let mut out = vec![]; let mut a: Vec<u8> = (0..n as u8).collect();
    fn rec(k: usize, a: &mut Vec<u8>, out: &mut Vec<P>) {
        if k == a.len() { let mut p = [0u8; MAXD]; for i in 0..MAXD { p[i] = i as u8; } for i in 0..a.len() { p[i] = a[i]; } out.push(p); return; }
        for i in k..a.len() { a.swap(k, i); rec(k + 1, a, out); a.swap(k, i); }
    }
    rec(0, &mut a, &mut out); out
}
fn partitions(n: usize, maxp: usize) -> Vec<Vec<usize>> {
    if n == 0 { return vec![vec![]]; }
    let mut out = vec![];
    for p in (1..=maxp.min(n)).rev() { for mut rest in partitions(n - p, p) { rest.insert(0, p); out.push(rest); } }
    out
}
fn class_rep(n: usize, parts: &[usize]) -> P {
    let mut p = [0u8; MAXD]; for i in 0..MAXD { p[i] = i as u8; }
    let mut s = 0; for &l in parts { for i in 0..l { p[s + i] = (s + (i + 1) % l) as u8; } s += l; } assert_eq!(s, n); p
}
fn ctype(cx: &Cx, p: &P) -> String { let mut c = cx.cyc_lens(p); c.retain(|&l| l > 1); c.sort_unstable_by(|a, b| b.cmp(a)); format!("{:?}", c) }
fn fmt_perm(cx: &Cx, p: &P) -> String {
    let mut seen = [false; MAXD]; let mut s = String::new();
    for i in 0..cx.n { if seen[i] { continue; } let mut c = vec![]; let mut x = i;
        while !seen[x] { seen[x] = true; c.push(x + 1); x = p[x] as usize; }
        if c.len() > 1 { s.push('('); s.push_str(&c.iter().map(|v| v.to_string()).collect::<Vec<_>>().join(" ")); s.push(')'); } }
    if s.is_empty() { "()".into() } else { s }
}

fn exhaust(n: usize, want_genus: usize) {
    // Seeds: every orbit has a state whose first entry has minimal index among
    // the four, so only such seeds are enumerated (g1 runs over class
    // representatives, g2 and g3 over all permutations).
    let cx = Cx { n }; let perms = all_perms(n);
    let pind: Vec<usize> = perms.iter().map(|p| cx.ind(p)).collect();
    let target = 2 * n - 2 + 2 * want_genus;
    let mut known: HashMap<Key, usize> = HashMap::new();
    let mut n_orbits = 0usize; let mut n_tuples = 0u64; let mut n_pass = 0u64;
    let mut summary: HashMap<(bool, bool, bool), usize> = HashMap::new();
    let t0 = std::time::Instant::now();
    for parts in partitions(n, n) {
        let g1 = class_rep(n, &parts); let i1 = cx.ind(&g1);
        if i1 == 0 || 4 * i1 > target { continue; }
        for (k2, g2) in perms.iter().enumerate() {
            let i2 = pind[k2]; if i2 < i1 || i1 + i2 + 2 * i1 > target { continue; }
            let p12 = cx.mul(&g1, g2);
            for (k3, g3) in perms.iter().enumerate() {
                let i3 = pind[k3]; if i3 < i1 || i1 + i2 + i3 + i1 > target { continue; }
                let q = cx.mul(&p12, g3); let i4 = cx.ind(&q);
                if i1 + i2 + i3 + i4 != target || i4 < i1 { continue; }
                let g4 = cx.inv(&q);
                let t = [g1, *g2, *g3, g4];
                if cx.orbits(&[&t[0], &t[1], &t[2]]).1 != 1 { continue; }
                n_tuples += 1;
                if !cusp(&cx, &t).0 { continue; }
                if !cusp(&cx, &[t[1], t[2], t[3], t[0]]).0 { continue; }
                n_pass += 1;
                let k = canonical(&cx, &t);
                if known.contains_key(&k) { continue; }
                let r = orbit(&cx, &t, 20_000_000, true).expect("cap");
                let id = n_orbits; n_orbits += 1;
                for s in &r.states { known.insert(*s, id); }
                *summary.entry((r.geo, r.comb, r.lam12_840 > 0)).or_insert(0) += 1;
                if r.geo {
                    let u = unpack(&cx, &r.states[0]);
                    println!("ORBIT d={} genus={} N={} geo_all_smooth=true comb_all_smooth={} 12lambda={}/840 types={} {} {} {} tuple=[{}; {}; {}; {}]",
                        n, want_genus, r.states.len(), r.comb, r.lam12_840,
                        ctype(&cx, &u[0]), ctype(&cx, &u[1]), ctype(&cx, &u[2]), ctype(&cx, &u[3]),
                        fmt_perm(&cx, &u[0]), fmt_perm(&cx, &u[1]), fmt_perm(&cx, &u[2]), fmt_perm(&cx, &u[3]));
                }
            }
        }
        eprintln!("  class {:?} done, {:.0}s, orbits so far {}", parts, t0.elapsed().as_secs_f64(), n_orbits);
    }
    let mut keys: Vec<_> = summary.into_iter().collect(); keys.sort();
    println!("SUMMARY d={} genus={} transitive identity-free min-index seeds {} (two-cusp geometric pass {}), orbits met {} in {:.1}s",
        n, want_genus, n_tuples, n_pass, n_orbits, t0.elapsed().as_secs_f64());
    for ((geo, comb, lp), c) in keys { println!("  geo_all_smooth {} comb_all_smooth {} lambda>0 {}: {} orbits", geo, comb, lp, c); }
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let get = |k: &str| args.iter().position(|a| a == k).map(|i| args[i + 1].clone());
    if args.iter().any(|a| a == "--exhaust") {
        let n: usize = get("--d").unwrap().parse().unwrap();
        let g: usize = get("--genus").unwrap().parse().unwrap();
        exhaust(n, g);
    } else {
        eprintln!("usage: geosmooth --exhaust --d D --genus G");
    }
}
