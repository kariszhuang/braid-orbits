from collections import deque
from verify_smooth_geometry import forced_partition, orbits, cycles, compose


def join(a,b,n):
    parent=list(range(n))
    def find(x):
        while parent[x]!=x:parent[x]=parent[parent[x]];x=parent[x]
        return x
    for parts in [a,b]:
        for block in parts:
            for x in block[1:]:
                u,v=find(block[0]),find(x)
                if u!=v:parent[max(u,v)]=min(u,v)
    groups={}
    for x in range(n):groups.setdefault(find(x),[]).append(x)
    return tuple(sorted(tuple(b) for b in groups.values()))


def block_lattice(t,cap=10000):
    n=len(t[0])
    if len(orbits(t))!=1:raise ValueError('transitive action required')
    bottom=tuple((x,) for x in range(n));atoms=sorted({forced_partition(t,[[0,x]]) for x in range(1,n)})
    seen={bottom};queue=deque([bottom]);complete=True
    while queue and complete:
        a=queue.popleft()
        for b in atoms:
            q=join(a,b,n)
            if q in seen:continue
            if len(seen)>=cap:complete=False;break
            seen.add(q);queue.append(q)
    g=1-n+sum(n-len(cycles(p)) for p in t)//2;systems=[]
    for blocks in sorted(seen):
        r=len(blocks)
        if r in [1,n]:continue
        k=len(blocks[0]);membership={x:i for i,b in enumerate(blocks) for x in b}
        if any(len(b)!=k for b in blocks):raise ValueError('unequal transitive blocks')
        q=[]
        for p in t:
            images=[{membership[p[x]] for x in b} for b in blocks]
            if any(len(v)!=1 for v in images):raise ValueError('noninvariant lattice join')
            q.append(tuple(next(iter(v)) for v in images))
        qi=[r-len(cycles(p)) for p in q];excess=[n-len(cycles(p))-k*i for p,i in zip(t,qi)]
        h=1-r+sum(qi)//2
        if h<0 or min(excess)<0 or g!=1+k*(h-1)+sum(excess)//2:raise ValueError('quotient genus identity')
        systems.append(dict(blocks=r,block_size=k,partition=[[x+1 for x in b] for b in blocks],
            genus=h,indices=qi,ramification_excess=excess,identity_entries=[i+1 for i,p in enumerate(q) if p==tuple(range(r))]))
    cores=[]
    for i,a in enumerate(systems):
        fine=[{x for x in b} for b in a['partition']]
        if not any(b['blocks']<a['blocks'] and all(any(s.issubset(set(c)) for c in b['partition']) for s in fine) for b in systems):cores.append(i)
    return dict(complete=complete,partitions_seen=len(seen),proper_systems=systems,
        primitive=(not systems) if complete else None,primitive_quotient_indices=cores if complete else None,
        proof='joins of all least invariant equivalences generated by(0,x); quotient genus is partition-dependent')
